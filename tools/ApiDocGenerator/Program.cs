using System.Text;
using System.Xml.Linq;

var config = args.Length > 0 ? args[0] : "Debug";
var repoRoot = FindRepoRoot();
var xmlFiles = new[]
{
    Path.Combine(repoRoot, $"Alis.Reactive/bin/{config}/net10.0/Alis.Reactive.xml"),
    Path.Combine(repoRoot, $"Alis.Reactive.Native/bin/{config}/net10.0/Alis.Reactive.Native.xml"),
    Path.Combine(repoRoot, $"Alis.Reactive.Fusion/bin/{config}/net10.0/Alis.Reactive.Fusion.xml"),
};
var outputPath = Path.Combine(repoRoot, "docs-site/src/content/docs/reference/api-reference.md");

var allMembers = new List<DocMember>();
foreach (var xmlFile in xmlFiles)
{
    if (!File.Exists(xmlFile))
    {
        Console.Error.WriteLine($"WARNING: XML file not found: {xmlFile}");
        Console.Error.WriteLine("Run 'dotnet build' first to generate XML documentation files.");
        continue;
    }

    var doc = XDocument.Load(xmlFile);
    var assemblyName = doc.Root?.Element("assembly")?.Element("name")?.Value ?? "Unknown";

    foreach (var member in doc.Descendants("member"))
    {
        var name = member.Attribute("name")?.Value;
        if (string.IsNullOrEmpty(name)) continue;

        allMembers.Add(new DocMember(name, assemblyName, member));
    }
}

if (allMembers.Count == 0)
{
    Console.Error.WriteLine("ERROR: No XML documentation members found. Run 'dotnet build' first.");
    return 1;
}

var publicMembers = allMembers
    .Where(m => !IsInternal(m))
    .ToList();

var types = publicMembers
    .Where(m => m.Kind == MemberKind.Type)
    .OrderBy(m => m.Namespace)
    .ThenBy(m => m.TypeName)
    .ToList();

var membersByType = publicMembers
    .Where(m => m.Kind != MemberKind.Type)
    .GroupBy(m => m.FullTypeName)
    .ToDictionary(g => g.Key, g => g.OrderBy(m => m.MemberName).ToList());

var markdown = new StringBuilder();
markdown.AppendLine("---");
markdown.AppendLine("title: API Reference");
markdown.AppendLine("description: Complete public API — every method, every overload, every signature. Auto-generated from XML documentation.");
markdown.AppendLine("sidebar:");
markdown.AppendLine("  order: 0");
markdown.AppendLine("---");
markdown.AppendLine();
markdown.AppendLine("<!-- AUTO-GENERATED by tools/ApiDocGenerator. Do not edit manually. -->");
markdown.AppendLine("<!-- Run: npm run build:api-docs -->");
markdown.AppendLine();
markdown.AppendLine("Complete public API for Alis.Reactive. Auto-generated from XML documentation comments.");
markdown.AppendLine("For usage and examples, see the [Grammar Tree](../../csharp-modules/mental-model/#the-grammar-tree) and the [Reactivity](../../csharp-modules/reactivity/triggers-and-reactions/) pages.");
markdown.AppendLine();

var byAssembly = types.GroupBy(t => t.Assembly).OrderBy(g => g.Key);
foreach (var assemblyGroup in byAssembly)
{
    var byNamespace = assemblyGroup.GroupBy(t => t.Namespace).OrderBy(g => g.Key);
    foreach (var nsGroup in byNamespace)
    {
        markdown.AppendLine($"## {SimplifyNamespace(nsGroup.Key)}");
        markdown.AppendLine();

        foreach (var docType in nsGroup)
        {
            markdown.AppendLine($"### {docType.DisplayTypeName}");
            markdown.AppendLine();

            var summary = GetSummaryText(docType.Element);
            if (!string.IsNullOrWhiteSpace(summary))
            {
                markdown.AppendLine(summary.Trim());
                markdown.AppendLine();
            }

            if (membersByType.TryGetValue(docType.FullTypeName, out var members))
            {
                var properties = members.Where(m => m.Kind == MemberKind.Property).ToList();
                var methods = members.Where(m => m.Kind == MemberKind.Method).ToList();

                if (properties.Count > 0)
                {
                    markdown.AppendLine("```csharp");
                    markdown.AppendLine("// Properties");
                    foreach (var property in properties)
                    {
                        var propertySummary = GetSummaryInline(property.Element);
                        markdown.AppendLine(string.IsNullOrWhiteSpace(propertySummary)
                            ? property.DisplaySignature
                            : $"{property.DisplaySignature}  // {propertySummary}");
                    }
                    markdown.AppendLine("```");
                    markdown.AppendLine();
                }

                if (methods.Count > 0)
                {
                    markdown.AppendLine("```csharp");
                    foreach (var method in methods)
                    {
                        markdown.AppendLine(method.DisplaySignature);
                    }
                    markdown.AppendLine("```");
                    markdown.AppendLine();
                }
            }
        }

        markdown.AppendLine("---");
        markdown.AppendLine();
    }
}

var outputDir = Path.GetDirectoryName(outputPath)!;
Directory.CreateDirectory(outputDir);
File.WriteAllText(outputPath, markdown.ToString().TrimEnd() + Environment.NewLine);

Console.WriteLine($"Generated API reference: {outputPath}");
Console.WriteLine($"  Types: {types.Count}");
Console.WriteLine($"  Members: {publicMembers.Count - types.Count}");
Console.WriteLine($"  From: {xmlFiles.Length} XML files");

return 0;

static string FindRepoRoot()
{
    var dir = Directory.GetCurrentDirectory();
    while (dir != null)
    {
        if (File.Exists(Path.Combine(dir, "package.json")) &&
            Directory.Exists(Path.Combine(dir, "Alis.Reactive")))
            return dir;
        dir = Directory.GetParent(dir)?.FullName;
    }
    return Directory.GetCurrentDirectory();
}

static bool IsInternal(DocMember m)
{
    var summary = m.Element.Element("summary")?.Value ?? "";
    if (summary.Contains("NEVER make public", StringComparison.OrdinalIgnoreCase))
        return true;
    if (m.Kind == MemberKind.Method && m.MemberName == "#ctor")
        return true;
    return false;
}

static string GetSummaryText(XElement member)
{
    var summary = member.Element("summary");
    if (summary == null) return "";
    return NormalizeDocText(CleanXmlText(summary));
}

static string GetSummaryInline(XElement member)
{
    var summary = member.Element("summary");
    if (summary == null) return "";
    return string.Join(" ", NormalizeDocText(CleanXmlText(summary))
        .Split('\n')
        .Select(line => line.Trim()));
}

static string NormalizeDocText(string text)
{
    var lines = text.Replace("\r\n", "\n").Split('\n')
        .Select(line => line.TrimEnd())
        .ToList();

    while (lines.Count > 0 && string.IsNullOrWhiteSpace(lines[0]))
        lines.RemoveAt(0);

    while (lines.Count > 0 && string.IsNullOrWhiteSpace(lines[^1]))
        lines.RemoveAt(lines.Count - 1);

    return string.Join(Environment.NewLine, lines);
}

static string CleanXmlText(XElement element)
{
    var markdown = new StringBuilder();
    foreach (var xmlNode in element.Nodes())
    {
        if (xmlNode is XText text)
        {
            markdown.Append(text.Value);
        }
        else if (xmlNode is XElement xmlElement)
        {
            switch (xmlElement.Name.LocalName)
            {
                case "c":
                    markdown.Append($"`{xmlElement.Value}`");
                    break;
                case "code":
                    markdown.AppendLine();
                    markdown.AppendLine("```csharp");
                    markdown.AppendLine(xmlElement.Value.Trim());
                    markdown.AppendLine("```");
                    break;
                case "see":
                    var cref = xmlElement.Attribute("cref")?.Value;
                    var langword = xmlElement.Attribute("langword")?.Value;
                    if (langword != null)
                        markdown.Append($"`{langword}`");
                    else if (cref != null)
                        markdown.Append($"`{SimplifyCref(cref)}`");
                    else
                        markdown.Append(xmlElement.Value);
                    break;
                case "para":
                    markdown.AppendLine();
                    markdown.Append(CleanXmlText(xmlElement));
                    break;
                case "paramref":
                    markdown.Append($"`{xmlElement.Attribute("name")?.Value}`");
                    break;
                case "typeparamref":
                    markdown.Append($"`{xmlElement.Attribute("name")?.Value}`");
                    break;
                case "b":
                    markdown.Append($"**{xmlElement.Value}**");
                    break;
                default:
                    markdown.Append(CleanXmlText(xmlElement));
                    break;
            }
        }
    }
    return markdown.ToString();
}

static string SimplifyCref(string cref)
{
    if (cref.Length > 2 && cref[1] == ':')
        cref = cref[2..];
    var lastDot = cref.LastIndexOf('.');
    if (lastDot >= 0) cref = cref[(lastDot + 1)..];
    return CleanGenericNotation(cref);
}

static string SimplifyNamespace(string ns)
{
    return ns.Replace("Alis.Reactive.", "").Replace(".", " — ");
}

static string CleanGenericNotation(string name)
{
    var genericArityMarkerIndex = name.IndexOf('`');
    if (genericArityMarkerIndex >= 0) return $"{name[..genericArityMarkerIndex]}<T>";
    return name;
}

enum MemberKind { Type, Method, Property, Field, Event }

record DocMember(string RawName, string Assembly, XElement Element)
{
    public MemberKind Kind => RawName[0] switch
    {
        'T' => MemberKind.Type,
        'M' => MemberKind.Method,
        'P' => MemberKind.Property,
        'F' => MemberKind.Field,
        'E' => MemberKind.Event,
        _ => MemberKind.Type,
    };

    public string FullName => RawName.Length > 2 ? RawName[2..] : RawName;

    public string FullTypeName
    {
        get
        {
            if (Kind == MemberKind.Type) return FullName;
            var name = FullName;
            var parameterListIndex = name.IndexOf('(');
            if (parameterListIndex >= 0) name = name[..parameterListIndex];
            var lastDot = name.LastIndexOf('.');
            return lastDot >= 0 ? name[..lastDot] : name;
        }
    }

    public string Namespace
    {
        get
        {
            var typeName = Kind == MemberKind.Type ? FullName : FullTypeName;
            var clean = typeName;
            var genericArityMarkerIndex = clean.IndexOf('`');
            if (genericArityMarkerIndex >= 0) clean = clean[..genericArityMarkerIndex];
            var lastDot = clean.LastIndexOf('.');
            return lastDot >= 0 ? clean[..lastDot] : "";
        }
    }

    public string TypeName
    {
        get
        {
            var typeName = Kind == MemberKind.Type ? FullName : FullTypeName;
            var lastDot = typeName.LastIndexOf('.');
            var name = lastDot >= 0 ? typeName[(lastDot + 1)..] : typeName;
            return CleanGeneric(name);
        }
    }

    public string DisplayTypeName => TypeName;

    public string MemberName
    {
        get
        {
            if (Kind == MemberKind.Type) return TypeName;
            var name = FullName;
            var parameterListIndex = name.IndexOf('(');
            if (parameterListIndex >= 0) name = name[..parameterListIndex];
            var lastDot = name.LastIndexOf('.');
            return lastDot >= 0 ? CleanGeneric(name[(lastDot + 1)..]) : CleanGeneric(name);
        }
    }

    public string DisplaySignature
    {
        get
        {
            if (Kind == MemberKind.Property)
                return $"{MemberName} {{ get; }}";

            if (Kind == MemberKind.Method)
            {
                var paramElements = Element.Elements("param").ToList();
                var paramList = string.Join(", ", paramElements.Select(p => p.Attribute("name")?.Value ?? "?"));
                return $"{MemberName}({paramList})";
            }

            return MemberName;
        }
    }

    private static string CleanGeneric(string name)
    {
        var genericArityMarkerIndex = name.IndexOf('`');
        if (genericArityMarkerIndex >= 0) return $"{name[..genericArityMarkerIndex]}<T>";
        return name;
    }
}
