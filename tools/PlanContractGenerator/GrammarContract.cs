using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using Alis.Reactive.Grammar;
using Alis.Reactive.Serialization;

namespace Alis.Reactive.ContractGeneration
{
    /// <summary>
    /// Writes the TypeScript plan contract (<c>runtime/types/plan.ts</c>) from the grammar's node
    /// classes: a union per polymorphic base, an interface per node with its <c>kind</c> literal, and a
    /// member per public property, camelCase, as <see cref="GrammarSerializer"/> writes them. The node
    /// classes are the only source, so a change to the grammar changes the contract.
    /// </summary>
    internal static class GrammarContract
    {
        private const string Header =
            "// <auto-generated />\n" +
            "// Generated by tools/PlanContractGenerator from the C# grammar (Alis.Reactive/Grammar).\n" +
            "// Do not edit by hand. Run `npm run generate:plan-types -w Alis.Reactive.Assets`.\n";

        internal static string Render()
        {
            var writer = new ContractWriter();
            writer.Declare(
                "JsonValue",
                "export type JsonValue =\n" +
                "  | string\n  | number\n  | boolean\n  | null\n  | JsonValue[]\n  | { [key: string]: JsonValue };");
            writer.Visit(typeof(GrammarPlan));
            writer.Declare("VendorPayload", LiteralUnion("VendorPayload",
                Enum.GetValues(typeof(VendorEventPayload)).Cast<VendorEventPayload>().Select(Vendor.PayloadOf)));
            writer.Declare("Operator", LiteralUnion("Operator", Operator.Table.Select(op => op.Token)));
            return Header + "\n" + writer.Text();
        }

        private static string LiteralUnion(string name, IEnumerable<string> values) =>
            "export type " + name + " =\n" + string.Join("\n", values.Select(v => "  | " + JsonSerializer.Serialize(v))) + ";";

        private sealed class ContractWriter
        {
            private readonly List<string> _blocks = new List<string>();
            private readonly HashSet<string> _declared = new HashSet<string>(StringComparer.Ordinal);

            internal string Text() => string.Join("\n\n", _blocks) + "\n";

            internal void Declare(string name, string block)
            {
                if (!_declared.Add(name)) return;
                _blocks.Add(block);
            }

            internal void Visit(Type type)
            {
                var name = TypeName(type);
                if (_declared.Contains(name)) return;

                if (IsUnion(type))
                {
                    var variants = Variants(type);
                    Declare(name, "export type " + name + " =\n" +
                        string.Join("\n", variants.Select(v => "  | " + TypeName(v))) + ";");
                    foreach (var variant in variants) Visit(variant);
                    return;
                }

                var properties = ContractProperties(type);
                var body = new StringBuilder();
                body.Append("export interface ").Append(name).Append(" {\n");
                foreach (var property in properties)
                    body.Append("  ").Append(MemberName(property)).Append(": ").Append(MemberType(property, type)).Append(";\n");
                body.Append("}");
                Declare(name, body.ToString());

                foreach (var property in properties)
                    foreach (var referenced in ReferencedNodeTypes(property.PropertyType))
                        Visit(referenced);
            }
        }

        private static bool IsUnion(Type type)
        {
            var converter = type.GetCustomAttribute<JsonConverterAttribute>();
            return type.IsAbstract
                && converter?.ConverterType != null
                && converter.ConverterType.IsGenericType
                && converter.ConverterType.GetGenericTypeDefinition() == typeof(PlanNodeDiscriminator<>);
        }

        private static List<Type> Variants(Type union) =>
            union.Assembly.GetTypes()
                .Where(t => !t.IsAbstract && union.IsAssignableFrom(t))
                .OrderBy(TypeName, StringComparer.Ordinal)
                .ToList();

        private static string TypeName(Type type) =>
            type == typeof(GrammarPlan) ? "PlanDocument" : type.Name;

        private static List<PropertyInfo> ContractProperties(Type type) =>
            type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                .Where(p => p.GetMethod != null && p.GetMethod.IsPublic)
                .Where(p => p.GetCustomAttribute<JsonIgnoreAttribute>() == null)
                .OrderBy(p => p.MetadataToken)
                .ToList();

        private static string MemberName(PropertyInfo property)
        {
            var declared = property.GetCustomAttribute<JsonPropertyNameAttribute>();
            return declared?.Name ?? JsonNamingPolicy.CamelCase.ConvertName(property.Name);
        }

        private static string MemberType(PropertyInfo property, Type owner)
        {
            var declared = property.GetCustomAttribute<ContractTypeAttribute>();
            if (declared != null) return declared.TypeScript;
            if (property.Name is "Kind" or "Version")
                return JsonSerializer.Serialize(ConstantOf(owner, property));
            return TypeScriptOf(property.PropertyType);
        }

        // A node declares its discriminator and the document its version as constants: the contract carries
        // each as a literal type, read without running a constructor.
        private static object ConstantOf(Type node, PropertyInfo property) =>
            property.GetValue(RuntimeHelpers.GetUninitializedObject(node))!;

        private static string TypeScriptOf(Type type)
        {
            if (type == typeof(string)) return "string";
            if (type == typeof(bool)) return "boolean";
            if (type == typeof(int) || type == typeof(long) || type == typeof(double)) return "number";
            if (TryElementOf(type, out var item)) return ArrayOf(TypeScriptOf(item));
            if (TryValueOf(type, out var value)) return "Record<string, " + TypeScriptOf(value) + ">";
            if (type.Namespace == typeof(GrammarPlan).Namespace) return TypeName(type);
            throw new InvalidOperationException("The grammar contract has no TypeScript type for " + type.FullName + ".");
        }

        private static string ArrayOf(string item) => item.Contains("|") ? "(" + item + ")[]" : item + "[]";

        private static IEnumerable<Type> ReferencedNodeTypes(Type type)
        {
            if (TryElementOf(type, out var item)) return ReferencedNodeTypes(item);
            if (TryValueOf(type, out var value)) return ReferencedNodeTypes(value);
            return type.Namespace == typeof(GrammarPlan).Namespace && type.IsClass && type != typeof(object)
                ? new[] { type }
                : Array.Empty<Type>();
        }

        private static bool TryElementOf(Type type, out Type item)
        {
            item = typeof(object);
            if (!type.IsGenericType || type.GetGenericTypeDefinition() != typeof(IReadOnlyList<>)) return false;
            item = type.GetGenericArguments()[0];
            return true;
        }

        private static bool TryValueOf(Type type, out Type value)
        {
            value = typeof(object);
            if (!type.IsGenericType || type.GetGenericTypeDefinition() != typeof(IReadOnlyDictionary<,>)) return false;
            value = type.GetGenericArguments()[1];
            return true;
        }
    }
}
