namespace Alis.Reactive.DesignSystem.Tokens
{
    /// <summary>
    /// Provides the responsive breakpoint widths used by the design system.
    /// </summary>
    public static class Breakpoints
    {
        /// <summary>Small breakpoint width in pixels.</summary>
        public const int Sm = 640;
        /// <summary>Medium breakpoint width in pixels.</summary>
        public const int Md = 768;
        /// <summary>Large breakpoint width in pixels.</summary>
        public const int Lg = 1024;
        /// <summary>Extra-large breakpoint width in pixels.</summary>
        public const int Xl = 1280;
        /// <summary>Double extra-large breakpoint width in pixels.</summary>
        public const int Xxl = 1536;
    }
}
