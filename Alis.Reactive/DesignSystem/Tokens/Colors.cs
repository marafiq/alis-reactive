namespace Alis.Reactive.DesignSystem.Tokens
{
    /// <summary>
    /// Defines accent color roles used by the design system.
    /// </summary>
    public enum AccentColor
    {
        /// <summary>Uses the primary accent color.</summary>
        Primary,
        /// <summary>Uses the secondary accent color.</summary>
        Secondary,
        /// <summary>Uses the success accent color.</summary>
        Success,
        /// <summary>Uses the warning accent color.</summary>
        Warning,
        /// <summary>Uses the error accent color.</summary>
        Error,
        /// <summary>Uses the informational accent color.</summary>
        Info,
        /// <summary>Uses the muted accent color.</summary>
        Muted
    }

    /// <summary>
    /// Defines text color roles used by the design system.
    /// </summary>
    public enum TextColor
    {
        /// <summary>Uses the primary text color.</summary>
        Primary,
        /// <summary>Uses the secondary text color.</summary>
        Secondary,
        /// <summary>Uses the muted text color.</summary>
        Muted,
        /// <summary>Uses the inverse text color for dark surfaces.</summary>
        Inverse,
        /// <summary>Uses the accent text color.</summary>
        Accent,
        /// <summary>Uses the success text color.</summary>
        Success,
        /// <summary>Uses the warning text color.</summary>
        Warning,
        /// <summary>Uses the error text color.</summary>
        Error,
        /// <summary>Inherits the text color from the parent element.</summary>
        Inherit
    }
}
