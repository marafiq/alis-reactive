namespace Alis.Reactive.DesignSystem.Tokens
{
    /// <summary>
    /// Defines the supported heading levels.
    /// </summary>
    public enum HeadingLevel
    {
        /// <summary>Renders an <c>h1</c> heading.</summary>
        H1 = 1,
        /// <summary>Renders an <c>h2</c> heading.</summary>
        H2 = 2,
        /// <summary>Renders an <c>h3</c> heading.</summary>
        H3 = 3,
        /// <summary>Renders an <c>h4</c> heading.</summary>
        H4 = 4,
        /// <summary>Renders an <c>h5</c> heading.</summary>
        H5 = 5,
        /// <summary>Renders an <c>h6</c> heading.</summary>
        H6 = 6
    }

    /// <summary>
    /// Defines the supported body text sizes.
    /// </summary>
    public enum TextSize
    {
        /// <summary>Uses the extra-small text size.</summary>
        Xs,
        /// <summary>Uses the small text size.</summary>
        Sm,
        /// <summary>Uses the base text size.</summary>
        Base,
        /// <summary>Uses the large text size.</summary>
        Lg,
        /// <summary>Uses the extra-large text size.</summary>
        Xl
    }
}
