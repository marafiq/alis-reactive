namespace Alis.Reactive.DesignSystem.Tokens
{
    /// <summary>
    /// Defines the spacing steps used by the design system.
    /// </summary>
    public enum SpacingScale
    {
        /// <summary>Applies no spacing.</summary>
        None,
        /// <summary>Applies the extra-small spacing step.</summary>
        Xs,
        /// <summary>Applies the small spacing step.</summary>
        Sm,
        /// <summary>Applies the base spacing step.</summary>
        Base,
        /// <summary>Applies the medium spacing step.</summary>
        Md,
        /// <summary>Applies the large spacing step.</summary>
        Lg,
        /// <summary>Applies the extra-large spacing step.</summary>
        Xl,
        /// <summary>Applies the double extra-large spacing step.</summary>
        Xxl,
        /// <summary>Applies the largest spacing step.</summary>
        Max
    }
}
